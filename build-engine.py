#!/usr/bin/env python3
"""Extracts the pure game logic from the game's HTML into server/engine.js.
Usage: python3 tools/build-engine.py ../Duel_Block_v30.html
Run again whenever you change piece generation / scoring rules in the game."""
import re, sys
src = open(sys.argv[1], encoding='utf-8').read().split('\n')
def find(prefix, start=0):
    for i in range(start, len(src)):
        if src[i].startswith(prefix): return i
    raise SystemExit('marker not found: ' + prefix)
def block(a, b_prefix, include_b=False):
    i = find(a); j = find(b_prefix, i)
    return '\n'.join(src[i:j + (1 if include_b else 0)])
head = block('const SH=[[', 'function mul', True)
core = block('function pcFrom', 'function full(', True)
plc  = block('function place(', 'function chk(')
out = f"""'use strict';
// AUTO-GENERATED by tools/build-engine.py from the game's HTML. Do not edit by hand.
const N=8,T=0;let shake=0,flash=0;const BX=0,BY=0,CS=1;
const _n={{push(){{}}}},beams=_n,dying=_n,floats=_n,rings=_n,parts=_n;
const SFX={{bomb(){{}},clear(){{}},place(){{}}}};const fmt=n=>String(n);function burst(){{}}
{head}
{core}
{plc}
function newGame(seed){{const p={{g:Array(64).fill(0),birth:Array(64).fill(-1e9),pcs:[],tray:[0,0,0],rng:mul(seed),score:0,ds:0,combo:0,ps:0,pop:-1e9,ver:0}};refill(p);return p}}
/* move = i*64 + r*8 + c ; returns false if illegal */
function applyMove(p,mv){{if(!Number.isInteger(mv)||mv<0||mv>=192)return false;const i=mv>>6,r=(mv>>3)&7,c=mv&7,pc=p.pcs[i];if(!pc||!fits(p,pc,r,c))return false;place(p,i,r,c);return true}}
function replay(seed,moves){{const p=newGame(seed);for(let k=0;k<moves.length;k++)if(!applyMove(p,moves[k]))return{{ok:false,at:k}};return{{ok:true,score:p.score,over:!anyMove(p),moves:moves.length}}}}
module.exports={{newGame,applyMove,replay,anyMove,fits}};
"""
open('engine.js', 'w', encoding='utf-8').write(out)
print('engine.js written', len(out), 'bytes')
